create table if not exists public.app_crash_reports (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete set null,
  app_version text not null default 'unknown',
  platform text not null check (platform in ('android', 'ios', 'web', 'macos', 'windows', 'linux')),
  error_type text not null check (length(error_type) between 1 and 160),
  message text not null check (length(message) <= 2000),
  stack_trace text not null default '' check (length(stack_trace) <= 8000),
  created_at timestamptz not null default now()
);

