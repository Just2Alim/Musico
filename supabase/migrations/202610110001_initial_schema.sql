create policy "Profiles are readable by owner" on public.profiles for select to authenticated using (id = (select auth.uid()));
create policy "Users manage own profile" on public.profiles for insert to authenticated with check (id = (select auth.uid()));
create policy "Users update own profile" on public.profiles for update to authenticated using (id = (select auth.uid())) with check (id = (select auth.uid()));
create policy "Tracks are visible to everyone" on public.tracks for select to anon, authenticated using (true);
create policy "Users read public or own playlists" on public.playlists for select to anon, authenticated using (is_public or user_id = (select auth.uid()));
create policy "Users create own playlists" on public.playlists for insert to authenticated with check (user_id = (select auth.uid()));
create policy "Users update own playlists" on public.playlists for update to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy "Users delete own playlists" on public.playlists for delete to authenticated using (user_id = (select auth.uid()));
create policy "Read tracks in visible playlists" on public.playlist_tracks for select to anon, authenticated using (
  exists (select 1 from public.playlists p where p.id = playlist_id and (p.is_public or p.user_id = (select auth.uid())))
);
create policy "Manage tracks in own playlist" on public.playlist_tracks for all to authenticated
  using (exists (select 1 from public.playlists p where p.id = playlist_id and p.user_id = (select auth.uid())))
  with check (exists (select 1 from public.playlists p where p.id = playlist_id and p.user_id = (select auth.uid())));
create policy "Users manage own favorites" on public.favorites for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy "Users manage own listening history" on public.listening_history for all to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy "Venues are visible to everyone" on public.venues for select to anon, authenticated using (true);
create policy "Users read own notifications" on public.notifications for select to authenticated using (user_id = (select auth.uid()));
create policy "Users update own notifications" on public.notifications for update to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));

